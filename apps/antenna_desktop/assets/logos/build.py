"""Generate lib/theme/ai_logos.dart from sources.json and the SVG marks next to it.

The window draws each mark from its SVG path data (lib/theme/svg_path.dart), so the SVG files stay the single source:
run this after adding or replacing a mark, and commit both. test/widget/ai_logos_test.dart checks that the generated
file matches the SVGs.

    python3 apps/antenna_desktop/assets/logos/build.py
"""

import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "lib" / "theme" / "ai_logos.dart"


def svg_mark(path: pathlib.Path) -> tuple[float, str]:
    text = path.read_text(encoding="utf-8")
    view = re.search(r'viewBox="0 0 ([0-9.]+) ([0-9.]+)"', text)
    paths = re.findall(r'<path[^>]* d="([^"]+)"', text)
    if not view or view.group(1) != view.group(2):
        raise SystemExit(f"{path.name}: expected a square viewBox starting at 0 0")
    if len(paths) != 1:
        raise SystemExit(f"{path.name}: expected exactly one <path>, found {len(paths)}")
    return float(view.group(1)), paths[0]


def main() -> None:
    src = json.loads((HERE / "sources.json").read_text(encoding="utf-8"))
    brands = src["brands"]
    lines = [
        # REUSE-IgnoreStart
        "// SPDX-License-Identifier: AGPL-3.0-only",
        # REUSE-IgnoreEnd
        "// GENERATED by assets/logos/build.py from assets/logos/sources.json and the SVG marks there. Do not edit by hand.",
        "// The marks belong to their owners and identify an integration only (assets/logos/README.md,",
        "// docs/CONNECT-APPS.md \"Marks\"). A brand without a mark is drawn as a neutral monogram.",
        "",
        "import 'dart:ui';",
        "",
        "/// The AI brands the window can name; [aiMarks] has a mark only where its use is allowed.",
        "enum AiBrand { " + ", ".join(b["brand"] for b in brands) + " }",
        "",
        "/// One mark: SVG path data in a square [viewBox], its colour on light and on dark tiles.",
        "final class AiMark {",
        "  const AiMark({required this.d, required this.onLight, required this.onDark, this.viewBox = 24});",
        "  final String d;",
        "  final Color onLight;",
        "  final Color onDark;",
        "  final double viewBox;",
        "}",
        "",
        "const aiMarks = <AiBrand, AiMark>{",
    ]
    for b in brands:
        if not b.get("svg"):
            continue
        view, d = svg_mark(HERE / b["svg"])
        lines += [
            f"  // {b['name']}: {b['source']}",
            f"  AiBrand.{b['brand']}: AiMark(",
            f"    viewBox: {view:g},",
            f"    onLight: Color(0xFF{b['on_light'].upper()}),",
            f"    onDark: Color(0xFF{b['on_dark'].upper()}),",
            f"    d: '{d}',",
            "  ),",
        ]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
